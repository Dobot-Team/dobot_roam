#!/usr/bin/env python3
"""
Build TensorRT engine from VLA LLM (hidden state mode) ONNX.

Supports FP32, FP16, and INT8 (with entropy calibration). When INT8 is enabled,
use calibration data generated by `calibrate_vla_inputs.py`.

NOTE: We initialize the cuda-python driver context *before* importing TensorRT
so that the builder and the INT8 calibrator share the same CUDA context.
"""
import argparse
import os
import sys
import warnings

import numpy as np

warnings.filterwarnings("ignore", category=DeprecationWarning)

_PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_ONNX = os.path.join(_PROJECT_ROOT, "deploy", "outputs", "vla_llm_hidden.onnx")
DEFAULT_OUTPUT = os.path.join(_PROJECT_ROOT, "deploy", "outputs", "vla_llm_hidden.trt")
DEFAULT_CALIB_DATA = os.path.join(_PROJECT_ROOT, "deploy", "outputs", "vla_llm_calib_data.npz")
DEFAULT_CALIB_CACHE = os.path.join(_PROJECT_ROOT, "deploy", "outputs", "vla_llm_hidden.cache")


def _init_cuda(must_succeed: bool = False):
    """Initialize cuda-python driver API and make a context current."""
    try:
        from cuda.bindings import driver as cuda
    except ImportError:
        if must_succeed:
            raise
        return None

    err = cuda.cuInit(0)
    if err[0] != cuda.CUresult.CUDA_SUCCESS:
        raise RuntimeError(f"cuInit failed: {err}")
    err, dev = cuda.cuDeviceGet(0)
    if err != cuda.CUresult.CUDA_SUCCESS:
        raise RuntimeError(f"cuDeviceGet failed: {err}")
    err, ctx = cuda.cuCtxCreate(None, 0, dev)
    if err != cuda.CUresult.CUDA_SUCCESS:
        raise RuntimeError(f"cuCtxCreate failed: {err}")
    return cuda


# Pre-bind a CUDA context so TensorRT and the calibrator share it.
_CUDA_MODULE = _init_cuda(must_succeed=False)

import tensorrt as trt  # noqa: E402


class Int8Calibrator(trt.IInt8EntropyCalibrator2):
    """TensorRT INT8 calibrator using pre-generated NumPy calibration data."""

    def __init__(self, calib_data_path: str, cache_path: str,
                 input_names: list, batch_size: int = 1):
        super().__init__()
        if not os.path.exists(calib_data_path):
            raise FileNotFoundError(f"Calibration data not found: {calib_data_path}. "
                                    f"Run `calibrate_vla_inputs.py` first.")

        data = np.load(calib_data_path)
        self.inputs_embeds = data["inputs_embeds"].astype(np.float32)
        self.attention_mask = data["attention_mask"].astype(np.int64)
        self.position_ids = data["position_ids"].astype(np.int64)
        self.seq_lens = data.get("seq_lens", None)

        self.batch_size = batch_size
        self.cache_path = cache_path
        self.input_names = input_names
        self.num_samples = self.inputs_embeds.shape[0]
        self.current_index = 0

        # Pre-allocate GPU buffers using cuda-python.
        if _CUDA_MODULE is None:
            raise RuntimeError("cuda-python is not available, cannot create INT8 calibrator.")
        self.cuda = _CUDA_MODULE
        _, self.buffers_embeds = self.cuda.cuMemAlloc(self.inputs_embeds[0:1].nbytes)
        _, self.buffers_mask = self.cuda.cuMemAlloc(self.attention_mask[0:1].nbytes)
        _, self.buffers_pos = self.cuda.cuMemAlloc(self.position_ids[0:1].nbytes)
        self.buffer_map = {
            "inputs_embeds": self.buffers_embeds,
            "attention_mask": self.buffers_mask,
            "position_ids": self.buffers_pos,
        }

    def get_batch_size(self):
        return self.batch_size

    def get_batch(self, names):
        if self.current_index >= self.num_samples:
            return None

        idx = self.current_index
        self.current_index += self.batch_size
        end = min(self.current_index, self.num_samples)

        batch_embeds = self.inputs_embeds[idx:end]
        batch_mask = self.attention_mask[idx:end]
        batch_pos = self.position_ids[idx:end]

        # Pad last incomplete batch by repeating the last sample.
        if end - idx < self.batch_size:
            pad = self.batch_size - (end - idx)
            batch_embeds = np.concatenate([batch_embeds] + [batch_embeds[-1:]] * pad, axis=0)
            batch_mask = np.concatenate([batch_mask] + [batch_mask[-1:]] * pad, axis=0)
            batch_pos = np.concatenate([batch_pos] + [batch_pos[-1:]] * pad, axis=0)

        self.cuda.cuMemcpyHtoD(self.buffers_embeds, batch_embeds.ctypes.data, batch_embeds.nbytes)
        self.cuda.cuMemcpyHtoD(self.buffers_mask, batch_mask.ctypes.data, batch_mask.nbytes)
        self.cuda.cuMemcpyHtoD(self.buffers_pos, batch_pos.ctypes.data, batch_pos.nbytes)

        return [int(self.buffer_map[name]) for name in names]

    def read_calibration_cache(self):
        if os.path.exists(self.cache_path):
            print(f"[Calibrator] Reading calibration cache: {self.cache_path}")
            with open(self.cache_path, "rb") as f:
                return f.read()
        return None

    def write_calibration_cache(self, cache):
        print(f"[Calibrator] Writing calibration cache: {self.cache_path}")
        with open(self.cache_path, "wb") as f:
            f.write(cache)


def build_engine(onnx_path: str, output_path: str, hidden_size: int = 896,
                 min_seq: int = 64, opt_seq: int = 512, max_seq: int = 2048,
                 fp16: bool = False, int8: bool = False,
                 calib_data_path: str = DEFAULT_CALIB_DATA,
                 calib_cache_path: str = DEFAULT_CALIB_CACHE,
                 workspace_mb: int = 4096):
    if not os.path.exists(onnx_path):
        print(f"[Error] ONNX not found: {onnx_path}")
        return 1

    if int8:
        if _CUDA_MODULE is None:
            print(f"[Error] INT8 calibration requires cuda-python. Install it with: "
                  f"{sys.executable} -m pip install cuda-python")
            return 1
        if not os.path.exists(calib_data_path):
            print(f"[Error] INT8 calibration data not found: {calib_data_path}\n"
                  f"        Generate it first: python deploy/vla/calibrate_vla_inputs.py")
            return 1

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    logger = trt.Logger(trt.Logger.INFO)
    builder = trt.Builder(logger)
    network = builder.create_network(1 << int(trt.NetworkDefinitionCreationFlag.EXPLICIT_BATCH))
    parser = trt.OnnxParser(network, logger)

    print(f"[Parse] Reading ONNX: {onnx_path}")
    if not parser.parse_from_file(onnx_path):
        for i in range(parser.num_errors):
            print(f"[ONNX Parse Error] {parser.get_error(i)}")
        return 1

    config = builder.create_builder_config()
    config.set_memory_pool_limit(trt.MemoryPoolType.WORKSPACE, workspace_mb * (1 << 20))

    if fp16:
        config.set_flag(trt.BuilderFlag.FP16)
        print("[Build] FP16 mode enabled.")
    if int8:
        config.set_flag(trt.BuilderFlag.INT8)
        print("[Build] INT8 mode enabled.")
        input_names = ["inputs_embeds", "attention_mask", "position_ids"]
        calibrator = Int8Calibrator(calib_data_path, calib_cache_path, input_names, batch_size=1)
        config.int8_calibrator = calibrator

    profile = builder.create_optimization_profile()
    profile.set_shape("inputs_embeds", (1, min_seq, hidden_size), (1, opt_seq, hidden_size), (1, max_seq, hidden_size))
    profile.set_shape("attention_mask", (1, min_seq), (1, opt_seq), (1, max_seq))
    profile.set_shape("position_ids", (1, min_seq), (1, opt_seq), (1, max_seq))
    config.add_optimization_profile(profile)

    print(f"[Profile] inputs_embeds: min=(1,{min_seq},{hidden_size}) opt=(1,{opt_seq},{hidden_size}) max=(1,{max_seq},{hidden_size})")
    print(f"[Build] Building TensorRT engine (workspace={workspace_mb}MB)...")
    serialized = builder.build_serialized_network(network, config)
    if serialized is None:
        print("[Error] Engine build failed.")
        return 1

    with open(output_path, "wb") as f:
        f.write(serialized)
    del serialized

    print(f"[Build] TensorRT engine saved: {output_path}")
    print(f"[Build] Engine size: {os.path.getsize(output_path) / (1<<20):.1f} MB")
    return 0


def main():
    parser = argparse.ArgumentParser(description="Build TensorRT engine for VLA LLM (hidden mode)")
    parser.add_argument("--onnx_path", type=str, default=DEFAULT_ONNX)
    parser.add_argument("--output", type=str, default=DEFAULT_OUTPUT)
    parser.add_argument("--hidden_size", type=int, default=896)
    parser.add_argument("--min_seq", type=int, default=64)
    parser.add_argument("--opt_seq", type=int, default=512)
    parser.add_argument("--max_seq", type=int, default=2048)
    parser.add_argument("--fp16", action="store_true", help="Enable FP16 precision")
    parser.add_argument("--int8", action="store_true", help="Enable INT8 quantization with calibration")
    parser.add_argument("--calib_data", type=str, default=DEFAULT_CALIB_DATA,
                        help="Path to calibration .npz generated by calibrate_vla_inputs.py")
    parser.add_argument("--calib_cache", type=str, default=DEFAULT_CALIB_CACHE,
                        help="Path to write/read TensorRT calibration cache")
    parser.add_argument("--workspace_mb", type=int, default=4096)
    args = parser.parse_args()

    sys.exit(build_engine(args.onnx_path, args.output, args.hidden_size,
                          args.min_seq, args.opt_seq, args.max_seq,
                          args.fp16, args.int8, args.calib_data, args.calib_cache,
                          args.workspace_mb))


if __name__ == "__main__":
    main()
